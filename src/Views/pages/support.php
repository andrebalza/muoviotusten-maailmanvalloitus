<section class="panel stack">
  <h2>Ongelmatilanteet</h2>
  <ul>
    <li>Tarkista, että laite on verkossa ja että kameraoikeus on sallittu.</li>
    <li>Jos asennus estetään, salli sovellusten asentaminen sille selaimelle tai tiedostonhallinnalle, jolla avasit APK:n.</li>
    <li>Älä poista sovellusta päivityksen yhteydessä. Asenna uudempi, samalla avaimella allekirjoitettu APK nykyisen version päälle.</li>
  </ul>
  <p>Ilmoita tekninen ongelma <a href="https://github.com/andrebalza/muoviotusten-maailmanvalloitus/issues">GitHub Issuesissa</a>. Gallerian sisältöön ja kuvan poistamiseen liittyvissä asioissa ota yhteyttä <a href="https://muoviamo.fi">Muoviamoon</a>.</p>
</section>

<section class="panel stack" lang="en">
  <h2>Troubleshooting</h2>
  <ul>
    <li>Check that the device is online and camera permission is allowed.</li>
    <li>If installation is blocked, allow app installation for the browser or file manager that opened the APK.</li>
    <li>Do not uninstall the app to update it. Install the newer APK signed with the same key over the existing version.</li>
  </ul>
  <p>Report technical problems through <a href="https://github.com/andrebalza/muoviotusten-maailmanvalloitus/issues">GitHub Issues</a>. For gallery content and image-removal requests, contact <a href="https://muoviamo.fi">Muoviamo</a>.</p>
</section>
